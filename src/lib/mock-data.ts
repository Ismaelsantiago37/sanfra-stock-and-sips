const iso = (daysAgo: number, hour = 20) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};

const future = (days: number) => iso(-days, 23);

