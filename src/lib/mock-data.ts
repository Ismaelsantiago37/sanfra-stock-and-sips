const orderItems = (ids: [string, number][]) =>
  ids.map(([id, quantity]) => {
    const p = products.find((x) => x.id === id)!;
    return { productId: p.id, name: p.name, unitPrice: p.price, quantity };
  });

const buildOrder = (
  n: number,
  customerId: string,
  items: [string, number][],
  status: OrderStatus,
  daysAgo: number,
  hour: number,
  type: "ENTREGA" | "RETIRADA" = "ENTREGA",
  paymentMethod: Order["paymentMethod"] = "PIX",
): Order => {
  const customer = customers.find((c) => c.id === customerId)!;
  const list = orderItems(items);
  const subtotal = list.reduce((s, i) => s + i.unitPrice * i.quantity, 0);
  const deliveryFee = type === "ENTREGA" ? 6 : 0;
  return {
    id: `o${n}`,
    number: n,
    customerId,
    customerName: customer.name,
    items: list,
    subtotal,
    deliveryFee,
    discount: 0,
    total: subtotal + deliveryFee,
    status,
    type,
    address: type === "ENTREGA" ? customer.address : undefined,
    paymentMethod,
    createdAt: iso(daysAgo, hour),
    etaMinutes: type === "ENTREGA" ? 40 : 20,
  };
};

